// Writes the SQL each SQL entry runs into the entry's own folder, systems/<entry>/sql/, so it can be read
// and reviewed without running anything.
//
//   node model/lib/sql/generate.mjs            writes the files
//   node model/lib/sql/generate.mjs --check    fails when a file is out of date
//
// schema.sql holds the empty tables and calculate.sql every calculated table. For each entry, members.sql,
// dimensions.sql and import/<Variable>.sql hold the load, and rebuild/<Variable>.sql what a write to an input
// variable must run. m1.sql and m4.sql are the migrations of tests M1
// and M4: only what a database built from calculate.sql must run to reach the changed model. M2 and M3 change members only, and the
// SQL never names a member that only the data brings, so they need no SQL of their own. The SQL does not depend
// on the dataset: members the model names have fixed ids (see dict.mjs), and the Versions and Years come
// from the data generator's own settings in data/params.mjs.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadModel, MONTHS, nullMember } from '../model.mjs';
import { changedModel } from '../changes.mjs';
import { params } from '../../../data/params.mjs';
import { translate } from './translate.mjs';
import { measuresSql } from './reads.mjs';
import { newDict, dimRows, SYSTEM_DIMS } from './dict.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const check = process.argv.includes('--check');

const t = params.time;
const firstYear = Number(t.firstMonth.slice(0, 4));
const system = {
    Versions: Object.keys(t.versions).sort(),
    Years: Array.from({ length: t.planYear - firstYear + 1 }, (_, i) => `Y${firstYear + i}`),
    Months: MONTHS,
};

// Each entry and the translator options it uses.
const ENTRIES = { 'duckdb-tables': {}, 'clickhouse-tables': { dialect: 'clickhouse' } };
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'fpabench-sql-'));
const MODELS = {
    base: path.join(root, 'model'),
    m1: (changedModel(path.join(root, 'model'), path.join(tmp, 'm1'), 'M1'), path.join(tmp, 'm1')),
    m4: (changedModel(path.join(root, 'model'), path.join(tmp, 'm4'), 'M4'), path.join(tmp, 'm4')),
};

/**
 * DuckDB's load, as SQL: the members the model brings, with fixed ids, then for each dimension the data's
 * own members from dimensions/<Dimension>.csv, and for each input variable its cells from
 * cells/<Variable>.csv. The paths are relative: the test points DuckDB's file_search_path at the folder of
 * input cells. Names become ids by a join on the
 * dimension tables. A name a dimension does not have stops the load.
 */
function duckdbLoad(model, dict) {
    const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;
    const q = (s) => `"${s}"`;
    const members = [];
    for (const d of [...model.userDims, ...SYSTEM_DIMS]) {
        const rows = dimRows(model, dict, d).map((r) => `(${r.map((x, k) => (k === 1 ? lit(x) : x)).join(', ')})`);
        if (rows.length) members.push(`INSERT INTO ${q(`dim ${d}`)} VALUES ${rows.join(', ')};`);
    }
    // Parents before children, so a member's parent ids exist when it goes in.
    const order = [];
    const visit = (d) => {
        if (order.includes(d)) return;
        for (const p of model.parentsOf(d)) visit(p);
        order.push(d);
    };
    model.userDims.forEach(visit);
    // The dimensions the data supplies: the ones the model has no member file for.
    const fromData = order.filter((d) => !fs.existsSync(path.join(root, 'model', 'dimensions', `${d}.csv`)));
    const dimensions = fromData.map((d) => {
        const parents = model.parentsOf(d);
        const cols = [`(SELECT coalesce(max(${q(d)}), 0) FROM ${q(`dim ${d}`)}) + row_number() OVER (ORDER BY c.${q(d)})`, `c.${q(d)}`];
        const joins = [];
        parents.forEach((p, k) => {
            joins.push(`LEFT JOIN ${q(`dim ${p}`)} p${k} ON p${k}.name = coalesce(nullif(c.${q(p)}, ''), ${lit(nullMember(p))})`);
            cols.push(`coalesce(p${k}.${q(p)}, error('${d} ' || c.${q(d)} || ' has a ${p} the dimension does not have: ' || c.${q(p)}))`);
        });
        return `-- ${d}\nINSERT INTO ${q(`dim ${d}`)} SELECT ${cols.join(', ')}\nFROM read_csv('dimensions/${d}.csv', header = true, all_varchar = true) c ${joins.join(' ')}\nWHERE c.${q(d)} NOT IN (SELECT name FROM ${q(`dim ${d}`)});\n`;
    });
    const imports = model.variables
        .filter((v) => !v.formula && !v.measure)
        .map((v) => {
            const keys = v.dims.map((d, k) => `coalesce(k${k}.${q(d)}, error('cells name a member ${d} does not have: ' || c.${q(d)}))`);
            const joins = v.dims.map((d, k) => `LEFT JOIN ${q(`dim ${d}`)} k${k} ON k${k}.name = c.${q(d)}`);
            return [
                v.name,
                `-- Generated by model/lib/sql/generate.mjs. Loads ${v.name} from cells/${v.name}.csv in the folder of input cells. Two rows for one cell add up.\nINSERT OR REPLACE INTO ${q(v.name)} SELECT ${[...keys, 'sum(c.value::DOUBLE)'].join(', ')}\nFROM read_csv('cells/${v.name}.csv', header = true, all_varchar = true) c ${joins.join(' ')}${keys.length ? `\nGROUP BY ALL` : ''};\n`,
            ];
        });
    return {
        'members.sql': `-- Generated by model/lib/sql/generate.mjs. The members the model itself brings, with fixed ids.\n${members.join('\n')}\n`,
        'dimensions.sql': `-- Generated by model/lib/sql/generate.mjs. The data's own members of each dimension, from dimensions/<Dimension>.csv in the folder of input cells,\n-- numbered after the model's members. Parents first, so a member's parent ids exist when it goes in.\n\n${dimensions.join('\n')}`,
        ...Object.fromEntries(imports.map(([v, text]) => [`import/${v}.sql`, text])),
    };
}

/**
 * ClickHouse's load, as SQL, in the same steps as DuckDB's. The input tables are ReplacingMergeTree, so each
 * row carries a version, the time of the insert in microseconds, and is_deleted = 0. The paths are relative:
 * the server's user_files_path is a folder of the work folder, and the test links the folder of input cells
 * into it. Every column of a CSV is read as text, so codes such as 0000100000 keep their leading zeros. A name
 * a dimension does not have stops the load.
 */
function clickhouseLoad(model, dict) {
    const lit = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
    const q = (s) => `"${s}"`;
    const csv = (file, cols) => `file(${lit(file)}, 'CSVWithNames', ${lit(cols.map((c) => `${q(c)} String`).join(', '))})`;
    const members = [];
    for (const d of [...model.userDims, ...SYSTEM_DIMS]) {
        const rows = dimRows(model, dict, d).map((r) => `(${r.map((x, k) => (k === 1 ? lit(x) : x)).join(', ')})`);
        if (rows.length) members.push(`INSERT INTO ${q(`dim ${d}`)} VALUES ${rows.join(', ')};`);
    }
    // Parents before children, so a member's parent ids exist when it goes in.
    const order = [];
    const visit = (d) => {
        if (order.includes(d)) return;
        for (const p of model.parentsOf(d)) visit(p);
        order.push(d);
    };
    model.userDims.forEach(visit);
    // The dimensions the data supplies: the ones the model has no member file for.
    const fromData = order.filter((d) => !fs.existsSync(path.join(root, 'model', 'dimensions', `${d}.csv`)));
    const dimensions = fromData.map((d) => {
        const parents = model.parentsOf(d);
        const cols = [`(SELECT coalesce(max(${q(d)}), 0) FROM ${q(`dim ${d}`)}) + row_number() OVER (ORDER BY c.${q(d)})`, `c.${q(d)}`];
        const joins = [];
        parents.forEach((p, k) => {
            joins.push(`LEFT JOIN ${q(`dim ${p}`)} p${k} ON p${k}.name = if(c.${q(p)} = '', ${lit(nullMember(p))}, c.${q(p)})`);
            cols.push(`coalesce(p${k}.${q(p)}, throwIf(isNull(p${k}.${q(p)}), ${lit(`a member of ${d} has a ${p} the dimension does not have`)}))`);
        });
        return `-- ${d}\nINSERT INTO ${q(`dim ${d}`)} SELECT ${cols.join(', ')}\nFROM ${csv(`dimensions/${d}.csv`, [d, ...parents])} c ${joins.join(' ')}\nWHERE c.${q(d)} NOT IN (SELECT name FROM ${q(`dim ${d}`)});\n`;
    });
    const imports = model.variables
        .filter((v) => !v.formula && !v.measure)
        .map((v) => {
            const keys = v.dims.map((d, k) => `coalesce(k${k}.${q(d)}, throwIf(isNull(k${k}.${q(d)}), ${lit(`cells name a member ${d} does not have`)}))`);
            const joins = v.dims.map((d, k) => `LEFT JOIN ${q(`dim ${d}`)} k${k} ON k${k}.name = c.${q(d)}`);
            return [
                v.name,
                `-- Generated by model/lib/sql/generate.mjs. Loads ${v.name} from cells/${v.name}.csv in the folder of input cells. Two rows for one cell add up.\nINSERT INTO ${q(v.name)} (${[...v.dims.map(q), 'v', 'ver', 'is_deleted'].join(', ')}) SELECT ${[...keys, 'sum(toFloat64(c.value))', 'toUnixTimestamp64Micro(now64(6))', '0'].join(', ')}\nFROM ${csv(`cells/${v.name}.csv`, [...v.dims, 'value'])} c ${joins.join(' ')}${keys.length ? `\nGROUP BY ALL` : ''};\n`,
            ];
        });
    return {
        'members.sql': `-- Generated by model/lib/sql/generate.mjs. The members the model itself brings, with fixed ids.\n${members.join('\n')}\n`,
        'dimensions.sql': `-- Generated by model/lib/sql/generate.mjs. The data's own members of each dimension, from dimensions/<Dimension>.csv in the folder of input cells,\n-- numbered after the model's members. Parents first, so a member's parent ids exist when it goes in.\n\n${dimensions.join('\n')}`,
        ...Object.fromEntries(imports.map(([v, text]) => [`import/${v}.sql`, text])),
    };
}

const files = new Map();
const stmts = (text) => new Set(text.split(/;\s*\n/).map((x) => x.trim()).filter(Boolean));
for (const [entry, options] of Object.entries(ENTRIES)) {
    const dialect = options.dialect ?? 'duckdb';
    const make = (dir) => {
        const model = loadModel(dir);
        return translate(model, { versions: system.Versions, years: system.Years, dict: newDict(model, system), ...options });
    };
    const base = make(MODELS.base);
    files.set(`${entry}/sql/schema.sql`, `-- Generated by model/lib/sql/generate.mjs, ${dialect} dialect. The empty tables: one per dimension, one per input variable.\n${base.schema.trim()}\n`);
    files.set(
        `${entry}/sql/calculate.sql`,
        [
            `-- Generated by model/lib/sql/generate.mjs, ${dialect} dialect. Builds every calculated table from the input tables.\n`,
            '-- The dimension lookups: one flattened table per dimension.',
            base.lookups.trim(),
            '',
            ...base.calculated.map((v, i) => `-- @table ${JSON.stringify(v)}\n${base.tables[i].trim()}\n`),
        ].join('\n')
    );
    {
        const model = loadModel(MODELS.base);
        const load = dialect === 'duckdb' ? duckdbLoad : clickhouseLoad;
        for (const [rel, text] of Object.entries(load(model, newDict(model, system)))) files.set(`${entry}/sql/${rel}`, text);
        // What a write to each input variable must run: every calculated table that reads it, directly or
        // through other tables, in dependency order.
        for (const v of model.variables.filter((v) => !v.formula && !v.measure)) {
            const steps = base.rebuildSql(new Set([v.name]));
            const names = base.calculated.filter((n, i) => steps.includes(base.tables[i]));
            files.set(
                `${entry}/sql/rebuild/${v.name}.sql`,
                [`-- Generated by model/lib/sql/generate.mjs. Run after a write to ${v.name}: the ${names.length} calculated tables it reaches, in dependency order.\n`, ...names.map((n, i) => `-- @table ${JSON.stringify(n)}\n${steps[i].trim()}\n`)].join('\n')
            );
        }
        // R4 reads every KPI measure of the report at once: one query per measure, side by side.
        const r4 = JSON.parse(fs.readFileSync(path.join(root, 'tests', 'tests.json'), 'utf8')).tests.find((x) => x.id === 'R4').read;
        const kpis = model.variables.filter((v) => v.measure && v.file === '8-report.fml');
        files.set(
            `${entry}/sql/reads/R4.sql`,
            `-- Generated by model/lib/sql/generate.mjs. Test R4: the ${kpis.length} KPI measures of 8-report.fml by ${r4.by.join(' and ')}, where ${Object.entries(r4.where).map(([d, m]) => `${d} is ${m}`).join(' and ')}.\n` +
                `-- It returns member ids, which the test turns into names.\n` +
                measuresSql(model, kpis.map((v) => v.name), { by: r4.by, where: r4.where }, dialect, newDict(model, system)) +
                ';\n'
        );
    }
    files.set(`${entry}/sql/base.json`, JSON.stringify({ model: 'base', dialect, system, calculated: base.calculated, reads: base.reads }, null, 1) + '\n');
    // A migration: from a database built from calculate.sql to the changed model. New input tables, then every
    // calculated table that is new or whose SQL changed, with every table that reads one of them, in order.
    const baseTable = new Map(base.calculated.map((v, i) => [v, base.tables[i].trim()]));
    const baseSchema = stmts(base.schema);
    for (const [name, dir] of Object.entries(MODELS)) {
        if (name === 'base') continue;
        const next = make(dir);
        const gone = base.calculated.filter((v) => !next.calculated.includes(v));
        if (gone.length) throw new Error(`${name} removes tables, which a migration does not do yet: ${gone.join(', ')}`);
        if (next.lookups.trim() !== base.lookups.trim()) throw new Error(`${name} changes the dimension lookups, which a migration does not do yet`);
        const newSchema = [...stmts(next.schema)].filter((x) => !baseSchema.has(x));
        const changed = next.calculated.filter((v, i) => baseTable.get(v) !== next.tables[i].trim());
        const steps = next.rebuildSql(new Set(changed));
        const stepNames = next.calculated.filter((v, i) => steps.includes(next.tables[i]));
        files.set(
            `${entry}/sql/${name}.sql`,
            [
                `-- Generated by model/lib/sql/generate.mjs: the migration of test ${name.toUpperCase()}, ${dialect} dialect. Do not edit.`,
                `-- It takes a database built from calculate.sql to the changed model. New or changed tables: ${changed.length}. Statements: ${steps.length}.\n`,
                '-- @schema: new input tables',
                newSchema.map((x) => `${x};`).join('\n'),
                '',
                ...stepNames.map((v, i) => `-- @table ${JSON.stringify(v)}${changed.includes(v) ? '' : ' (reads a changed table)'}\n${steps[i].trim()}\n`),
            ].join('\n')
        );
        files.set(`${entry}/sql/${name}.json`, JSON.stringify({ model: name, dialect, system, changed, tables: stepNames }, null, 1) + '\n');
    }
}
fs.rmSync(tmp, { recursive: true, force: true });

let stale = 0;
for (const [rel, text] of files) {
    const file = path.join(root, 'systems', rel);
    const now = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (now === text) continue;
    if (check) {
        console.error(`${rel} is out of date. Run: node model/lib/sql/generate.mjs`);
        stale++;
        continue;
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
}
if (stale) process.exit(1);
if (!check) console.log(`Wrote ${files.size} files to systems/<entry>/sql/`);
